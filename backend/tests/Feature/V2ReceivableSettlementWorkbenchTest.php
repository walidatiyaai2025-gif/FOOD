        }

        $this->assertDatabaseCount('enterprise_ar_allocations', 0);
        $this->assertDatabaseCount('enterprise_finance_journals', 1);
        $this->assertSame('posted', $document->fresh()->status);
        $this->assertDatabaseMissing('audit_logs', [
