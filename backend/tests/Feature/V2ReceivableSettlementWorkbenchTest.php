    public function test_collection_wallet_mapping_foreign_keys_use_short_mysql_names_and_completed_replay_is_idempotent(): void
    {
        $path = database_path('migrations/2026_11_16_020000_create_enterprise_finance_collection_account_mappings.php');
        $source = file_get_contents($path);
        $this->assertIsString($source);
        $foreignKeys = [
            'collection_account_id' => ['collection_accounts', 'efcam_collection_fk'],
            'finance_account_id' => ['enterprise_finance_accounts', 'efcam_finance_fk'],
            'store_id' => ['stores', 'efcam_store_fk'],
            'proposed_by' => ['users', 'efcam_proposer_fk'],
            'reviewed_by' => ['users', 'efcam_reviewer_fk'],
        ];

        foreach ($foreignKeys as $field => [$referenced, $name]) {
            $this->assertLessThanOrEqual(64, strlen($name));
            $this->assertStringContainsString(
                "constrained('{$referenced}', 'id', '{$name}')",
                $source,
                "The {$field} constraint name must be explicit: MySQL rejects Laravel's long autogenerated table prefix.",
            );
        }

        // Replaying a completed CREATE TABLE migration is a no-op and must
        // not duplicate the foreign keys or indexes after a retry.
        $migration = require $path;
        $migration->up();
        $migration->up();
        $actual = collect(Schema::getForeignKeys('enterprise_finance_collection_account_mappings'));
        $this->assertCount(5, $actual);

        if (DB::getDriverName() === 'mysql') {
            foreach ($foreignKeys as [, $name]) {
                $this->assertContains($name, $actual->pluck('name')->all());
            }
        }
    }

